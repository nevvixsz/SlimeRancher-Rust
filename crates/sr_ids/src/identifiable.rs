    /// Exact port of `Identifiable.Combine(List<Identifiable.Id>)`.
    /// Combines two base `_SLIME` IDs into their corresponding `_LARGO` (or `TarrSlime` if none exists).
    pub fn combine(ids: &[Self]) -> Option<Self> {
        match ids.len() {
            0 => Some(Self::None),
            1 => Some(ids[0]),
            2 => {
                let n0 = ids[0].as_csharp_name();
                let n1 = ids[1].as_csharp_name();
                let s0 = n0.strip_suffix("_SLIME")?;
                let s1 = n1.strip_suffix("_SLIME")?;
                let cand1 = format!("{s0}_{s1}_LARGO");
                if let Some(largo) = Self::from_name(&cand1) {
                    return Some(largo);
                }
                let cand2 = format!("{s1}_{s0}_LARGO");
                if let Some(largo) = Self::from_name(&cand2) {
                    return Some(largo);
                }
                Some(Self::TarrSlime)
            }
            _ => Some(Self::TarrSlime),
        }
    }

    /// Exact port of `SlimeEat.GetFoodGroupIds(FoodGroup)`.
    pub fn ids_in_food_group(group: crate::FoodGroup) -> Vec<Self> {
        use crate::FoodGroup;
        match group {
            FoodGroup::Veggies => Self::ALL.iter().copied().filter(|id| id.is_veggie()).collect(),
            FoodGroup::Fruit => Self::ALL.iter().copied().filter(|id| id.is_fruit()).collect(),
            FoodGroup::Meat => Self::ALL.iter().copied().filter(|id| id.is_meat()).collect(),
            FoodGroup::NontarrgoldSlimes => Self::ALL
                .iter()
                .copied()
                .filter(|id| id.is_slime() && !id.is_tarr() && *id != Self::GoldSlime && *id != Self::LuckySlime)
                .collect(),
            FoodGroup::Plorts => Self::ALL
                .iter()
                .copied()
                .filter(|id| id.is_plort() && *id != Self::PuddlePlort && *id != Self::GoldPlort && *id != Self::FirePlort)
                .collect(),
            FoodGroup::Ginger => vec![Self::GingerVeggie],
        }
    }
